def add_image(f,**changes):
    ident=str(uuid4());o=f['snapshot']['origin']
    values={'conv':o['conversation_id'],'org':None,'role':'user','status':'completed','kind':'conversation','revision':None,
            'content':[{'type':'image','workspace_path':'A.png','name':'A.png'}],**changes}
    with psycopg.connect(f['dsn']) as db:
        db.execute('INSERT INTO messages(id,conversation_id,org_id,role,content,status,message_kind,context_revision) VALUES (%s,%s,%s,%s,%s,%s,%s,%s)',
            (ident,values['conv'],values['org'],values['role'],json.dumps(values['content']),values['status'],values['kind'],values['revision']))
    return ident

def catalog(f):
    with psycopg.connect(f['dsn']) as db:return db.execute("SELECT request_params->'_image_sources_v1' FROM tasks WHERE id=%s",(f['parent'],)).fetchone()[0]

def actor_claim(f,branch=False):
    with connection(f) as db:return db.execute('SELECT claim_branch_generation_turn(%s)' if branch else 'SELECT claim_next_serial_generation_turn(%s)',
        (f['parent'] if branch else f['snapshot']['origin']['conversation_id'],)).fetchone()[0]

@pytest.mark.parametrize('branch',[False,True])
def test_atomic_sources_exclude_unclosed_foreign_internal_and_future_and_reclaim_never_widens(source_facts,branch):
    f=source_facts;good=add_image(f)
    for changes in ({'status':'pending'},{'status':'failed'},{'kind':'tool_internal'},{'org':str(uuid4())},{'conv':str(uuid4())},{'revision':1}):add_image(f,**changes)
    with psycopg.connect(f['dsn']) as db:
        # Inserted forged private JSON is overwritten on first claim.
        db.execute('UPDATE tasks SET execution_mode=%s WHERE id=%s',('branch' if branch else 'serial',f['parent']))
    assert actor_claim(f,branch)['outcome']=='claimed';frozen=deepcopy(catalog(f))
    assert [row['id'] for row in frozen['messages']]==[good]
    add_image(f)
    with psycopg.connect(f['dsn']) as db:
        db.execute("UPDATE messages SET status='completed' WHERE conversation_id=%s AND status='pending'",(f['snapshot']['origin']['conversation_id'],))
        db.execute('UPDATE conversations SET context_revision=8 WHERE id=%s',(f['snapshot']['origin']['conversation_id'],))
        db.execute("UPDATE tasks SET lease_expires_at=NOW()-INTERVAL '1 second' WHERE id=%s",(f['parent'],))
    assert actor_claim(f,branch)['base_context_revision']==0
    assert catalog(f)==frozen

def test_concurrent_claim_once(source_facts):
    f=source_facts;good=add_image(f)
    with ThreadPoolExecutor(max_workers=2) as pool:results=list(pool.map(lambda _:actor_claim(f),range(2)))
    assert sorted(row['outcome'] for row in results)==['busy','claimed']
    assert [row['id'] for row in catalog(f)['messages']]==[good]

def test_catalog_private_updates_cannot_replace_after_claim(source_facts):
    f=source_facts;add_image(f);actor_claim(f)
    for value in ({'version':1,'messages':[]},None):
        with pytest.raises(psycopg.Error,match='IMAGE_SOURCE_CATALOG_IMMUTABLE'):
            with connection(f) as db:db.execute("UPDATE tasks SET request_params=jsonb_set(request_params,'{_image_sources_v1}',%s) WHERE id=%s",(Jsonb(value),f['parent']))
    with connection(f) as db:db.execute("UPDATE tasks SET request_params=request_params || '{\"checkpoint\":true}' WHERE id=%s",(f['parent'],))
    assert len(catalog(f)['messages'])==1

