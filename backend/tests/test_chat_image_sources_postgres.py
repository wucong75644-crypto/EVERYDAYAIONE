def test_catalog_scope_and_immutability_do_not_depend_on_legacy_table_rls(source_facts):
    """Production legacy tables use trusted services, not table-level RLS."""
    f=source_facts;good=add_image(f)
    add_image(f,org=str(uuid4()));add_image(f,conv=str(uuid4()))
    db=psycopg.connect(f['dsn'])
    try:
        for table in ('tasks','messages','conversations'):
            db.execute(f'ALTER TABLE {table} DISABLE ROW LEVEL SECURITY')
        db.execute('SET LOCAL ROLE everydayai')
        db.execute("SELECT set_config('app.actor_user_id',%s,true),set_config('app.org_id','',true),set_config('app.access_kind','runtime',true)",(f['user'],))
        claim=db.execute('SELECT claim_next_serial_generation_turn(%s)',(f['snapshot']['origin']['conversation_id'],)).fetchone()[0]
        assert claim['outcome']=='claimed'
        frozen=db.execute("SELECT request_params->'_image_sources_v1' FROM tasks WHERE id=%s",(f['parent'],)).fetchone()[0]
        assert [row['id'] for row in frozen['messages']]==[good]
        with pytest.raises(psycopg.Error,match='IMAGE_SOURCE_CATALOG_IMMUTABLE'):
            with db.transaction():
                db.execute("UPDATE tasks SET request_params=jsonb_set(request_params,'{_image_sources_v1}','{}') WHERE id=%s",(f['parent'],))
        with pytest.raises(psycopg.Error,match='IMAGE_SOURCE_CATALOG_SCOPE_DENIED'):
            with db.transaction():
                db.execute("SELECT freeze_chat_image_sources(jsonb_populate_record(t,jsonb_build_object('user_id',%s::uuid)),c) FROM tasks t JOIN conversations c ON c.id=t.conversation_id WHERE t.id=%s",(str(uuid4()),f['parent']))
        for spoof in ('actor','org','token'):
            with pytest.raises(psycopg.Error,match='CHAT_IMAGE_(SCOPE_DENIED|PARENT_DENIED|FENCING_LOST)'):
                with db.transaction():
                    if spoof in ('actor','org'):
                        setting='app.actor_user_id' if spoof=='actor' else 'app.org_id'
                        db.execute('SELECT set_config(%s,%s,true)',(setting,str(uuid4())))
                    token=str(uuid4()) if spoof=='token' else claim['execution_token']
                    db.execute('SELECT accept_chat_image_request(%s,%s,%s,NULL)',(f['parent'],token,Jsonb(f['snapshot'])))
        assert db.execute("SELECT count(*) FROM tasks WHERE type='image' AND conversation_id=%s",(f['snapshot']['origin']['conversation_id'],)).fetchone()[0]==0
        assert db.execute('SELECT count(*) FROM credit_transactions WHERE user_id=%s',(f['user'],)).fetchone()[0]==0
        assert db.execute('SELECT credits FROM users WHERE id=%s',(f['user'],)).fetchone()[0]==100
    finally:
        # Test-only RLS toggles/claim are rolled back; no shared schema change.
        db.rollback();db.close()
